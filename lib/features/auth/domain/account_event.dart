/// Итог попытки привязки или входа, который нужно показать пользователю.
enum AccountEvent {
  /// Google уже привязан к другому аккаунту: предложить войти в него.
  conflict,

  /// Пользователь отказался на стороне Google.
  cancelled,

  /// Google не настроен в этой сборке или на сервере.
  unavailable,

  /// Нет сети или сервер недоступен.
  network,

  /// Что-то пошло не так.
  failed,
}
