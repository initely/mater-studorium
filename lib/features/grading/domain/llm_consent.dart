/// Согласие пользователя на отправку открытых ответов внешней модели
/// (ТЗ M5, карточка T16: однократный диалог перед первым `open`).
enum LlmConsent {
  /// Ещё не спрашивали: перед первым `open` покажем диалог.
  unknown,

  /// Разрешено: ответы уходят на проверку.
  granted,

  /// Отказ («без ИИ»): ответ не отправляется, пользователь оценивает себя
  /// сам с эталоном. Передумать можно в настройках.
  declined,
}

/// Хранилище согласия на устройстве. Ошибки хранилища — `LocalStorageError`.
abstract interface class LlmConsentRepository {
  Future<LlmConsent> load();

  Future<void> save(LlmConsent consent);
}
