/// Можно ли вообще диктовать на этом устройстве (без запроса разрешения).
enum SpeechSupport {
  /// Распознавание есть (или его наличие выяснится при первом запуске: на
  /// Android проверка требует разрешения на микрофон, а просить его при
  /// открытии вопроса нельзя).
  available,

  /// Распознавания нет (браузер без Web Speech API, на устройстве нет
  /// сервиса распознавания): кнопка микрофона недоступна.
  unsupported,
}

/// Почему диктовка не состоялась (ТЗ §8.3).
enum SpeechFailure {
  /// Нет разрешения на микрофон (отказ пользователя или браузера).
  permissionDenied,

  /// Распознавания нет на этом устройстве или в браузере.
  unsupported,

  /// Ничего не расслышали или речи не было (таймаут тишины).
  noSpeech,

  /// Сервису распознавания нужна сеть, её нет.
  network,

  /// Для языка колоды нет распознавания на устройстве.
  languageUnavailable,

  /// Остальное (занят микрофон, сбой сервиса).
  other,
}

/// Очередной результат диктовки: весь распознанный текст сессии (а не
/// приращение), как его отдают платформенные сервисы.
class SpeechUpdate {
  const SpeechUpdate(this.text, {this.isFinal = false});

  final String text;

  /// Окончательный результат (частичные результаты обновляются на лету).
  final bool isFinal;
}

/// Диктовка не удалась: приходит в поток [SpeechService.listen] как ошибка.
class SpeechException implements Exception {
  const SpeechException(this.failure);

  final SpeechFailure failure;

  @override
  String toString() => 'SpeechException($failure)';
}

/// Диктовка на устройстве (`speech_to_text`, ТЗ §8.3). Реализация в `data/`,
/// в тестах подменяется fake.
///
/// Звук не пишется и никуда не отправляется приложением: наружу выходит
/// только распознанный текст, и только пока пользователь держит сессию
/// диктовки (тап по микрофону). Платформенный сервис распознавания сам может
/// использовать сеть (Android, Chrome), это нужно сказать пользователю.
abstract interface class SpeechService {
  /// Есть ли распознавание; разрешение не запрашивает.
  Future<SpeechSupport> support();

  /// Начинает сессию диктовки на языке [lang] (код языка колоды, `ru`).
  /// Поток выдаёт частичные и итоговый результаты и закрывается, когда
  /// сессия закончилась (пауза в речи, [stop], [cancel], лимит времени);
  /// сбой приходит как [SpeechException] и тоже закрывает поток.
  Stream<SpeechUpdate> listen({required String lang});

  /// Завершает сессию: итоговый результат придёт в поток, затем он закроется.
  Future<void> stop();

  /// Прерывает сессию без итогового результата; поток закрывается.
  Future<void> cancel();
}

/// Переход в системные настройки приложения (если отказали в разрешении на
/// микрофон насовсем, только там его можно включить).
abstract interface class AppSettingsOpener {
  /// Платформа умеет открывать настройки приложения (Android).
  bool get isSupported;

  Future<void> openAppSettings();
}
