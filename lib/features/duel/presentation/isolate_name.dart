/// Первый и последний знаки изоляции направления текста (FSI и PDI, ревью T22
/// N5): имя соперника может быть написано справа налево, и без изоляции оно
/// переставило бы соседний текст («Дуэль с ...») в строке. Escape-
/// последовательностями, чтобы исходник не содержал bidi-символов буквально.
const _firstStrongIsolate = '\u2068';
const _popDirectionalIsolate = '\u2069';

/// Имя другого участника для вставки в строку интерфейса: в изоляции
/// направления текста. Имена приходят от соперника и проверены сервером
/// (`profiles_display_name_clean`), но направление письма они менять могут.
String isolateName(String name) =>
    '$_firstStrongIsolate$name$_popDirectionalIsolate';
