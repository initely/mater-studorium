/// Устойчивое зерно по строке: одинаково при каждом запуске (в отличие от
/// `String.hashCode`, который не обязан совпадать между запусками и
/// платформами). Для детерминированного перемешивания по ключу вида
/// `question_id|дата`. Полиномиальный хеш по кодовым единицам, 31 бит;
/// произведения остаются точными и на web (меньше 2^53).
int stableSeed(String key) {
  var hash = 17;
  for (final unit in key.codeUnits) {
    hash = (hash * 31 + unit) & 0x7fffffff;
  }
  return hash;
}
